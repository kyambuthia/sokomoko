var (
	viewBoxRE = regexp.MustCompile(`viewBox="([^"]+)"`)
	bodyRE    = regexp.MustCompile(`(?s)<svg[^>]*>(.*)</svg>`)
	boundsRE  = regexp.MustCompile(`<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>`)
	spaceRE   = regexp.MustCompile(`\s+`)
)

func main() {
	client := &http.Client{Timeout: 20 * time.Second}
	var b strings.Builder
	b.WriteString("<!-- Generated by scripts/iconsprite from Tabler Icons " + version + " (MIT). Do not edit. -->\n")
	b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg">` + "\n")
	for _, icon := range icons {
		raw := fetch(client, source+"/icons/outline/"+icon[1]+".svg")
		viewBox := viewBoxRE.FindStringSubmatch(raw)
		body := bodyRE.FindStringSubmatch(raw)
		if viewBox == nil || body == nil {
			log.Fatalf("unexpected SVG for %s", icon[1])
		}
		inner := strings.TrimSpace(spaceRE.ReplaceAllString(boundsRE.ReplaceAllString(body[1], ""), " "))
		fmt.Fprintf(&b, `<symbol id="i-%s" viewBox="%s">%s</symbol>`+"\n", icon[0], viewBox[1], inner)
	}
	b.WriteString("</svg>\n")
	write(output, b.String())
	write(license, fetch(client, source+"/LICENSE"))
	log.Printf("wrote %d icons to %s", len(icons), output)
}

func fetch(client *http.Client, url string) string {
	resp, err := client.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return string(body)
}

func write(path, content string) {
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		log.Fatal(err)
	}
}
